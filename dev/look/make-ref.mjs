// Lift the approved character's drawing code out of sun-final.html ONCE and
// write it where every other page can include it:
//
//   sun-char.js   - the drawing code alone, as a script any page can load
//   sun-ref.html  - him at 900px, alone, so a clean PNG can be taken of him
//
// Two consumers, one lift. A hand copy is exactly how a character ends up with
// two authors, and the acts check already exists because of that risk.
import fs from 'node:fs';

const DIR = 'C:/Projects/Nutrition-/dev/look/';
const fin = fs.readFileSync(DIR + 'sun-final.html', 'utf8');
const script = fin.match(/<script>([\s\S]*?)<\/script>/)[1];
const cut = script.indexOf('function stage(');
if (cut < 0) throw new Error('sun-final.html no longer defines stage() - check the file');
const draw = script.slice(0, cut).trimEnd();

if (!/function sunSVG\(px\)/.test(draw)) throw new Error('sunSVG not in the lifted slice');
if (draw.length < 1500) throw new Error('lifted slice is suspiciously short: ' + draw.length);

const banner = `/* GENERATED by dev/look/make-ref.mjs - do not edit.
   Lifted verbatim from sun-final.html, everything above function stage().
   Edit the character THERE and run the script again. */\n`;

fs.writeFileSync(DIR + 'sun-char.js', banner + draw + '\n');

fs.writeFileSync(DIR + 'sun-ref.html', `<!doctype html>
<html lang="he" dir="rtl">
<meta charset="utf-8">
<title>השמש — ייחוס</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<!--
  THE REFERENCE IMAGE. The approved character, 900px, alone on the app's ground,
  so a clean picture can be taken of him and handed to an image model as the
  thing to keep.

  The drawing code is not here: it is sun-char.js, generated by make-ref.mjs
  from sun-final.html. A reference image drawn from a HAND COPY of the character
  would be worse than no reference at all - it would quietly teach the model a
  slightly different sun, and every option that came back would be wrong in a
  way nobody could name.

  No blink keyframes are defined, so the eyes stay open.
-->
<style>
  html,body{margin:0;height:100%;background:#e9e7e3}
  body{display:grid;place-items:center}
  #ref{width:900px;height:900px}
  .sm{display:block;width:100%;height:100%;overflow:visible}
</style>
<div id="ref"></div>
<script src="sun-char.js"></script>
<script>document.getElementById('ref').innerHTML = sunSVG(900);</script>
</html>
`);

console.log('wrote dev/look/sun-char.js  (' + draw.length + ' chars lifted)');
console.log('wrote dev/look/sun-ref.html');
console.log('RR  = ' + (draw.match(/RR = \[([^\]]+)\]/) || [])[1]);
console.log('R   = ' + (draw.match(/R = ([\d.]+)/) || [])[1]);
console.log('dots at >=48px: ' + (/n = big \? 26 : 14/.test(draw) ? '26, width 2.6' : 'CHANGED'));
