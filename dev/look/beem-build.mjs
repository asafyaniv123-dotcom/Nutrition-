// Builds dev/look/beem-app.js - Beem for the app, in ONE closure.
//
//     node dev/look/beem-build.mjs
//
// WHY A BUNDLE AND NOT THE FILES. The Beem files declare 58 top-level names,
// and two of them - `G` and `once` - are also declared in dev/index.html.
// Loaded side by side, one would silently replace the other (a shadowed
// deleteGoal once ate goals here). So the app never loads the raw files:
// this wraps engine + special + alive + moon + streak in one function and
// lets exactly one name out, `BeemKit`. The pages under dev/look keep using
// the raw files, so the character sheet is untouched by this.
//
// Do not edit beem-app.js by hand; edit the sources and rebuild.
import fs from 'node:fs';
const L = new URL('.', import.meta.url).pathname.replace(/^\/(\w:)/, '$1');
const SRC = ['beem-engine.js', 'beem-special.js', 'beem-alive.js', 'beem-moon.js', 'beem-streak.js', 'beem-pair.js', 'beem-colors.js', 'beem-screen.js'];

let body = SRC.map(f => '/* ═══ ' + f + ' ═══ */\n' + fs.readFileSync(L + f, 'utf8')).join('\n');

// 1. the asset folder comes from the app (liveBase()), not from dev/look's '../assets/'
const before = "var ASSET = '../assets/';";
if (!body.includes(before)) throw new Error('asset line not found - the engine changed; update the build');
body = body.replace(before, "var ASSET = (typeof BEEM_ASSET_BASE === 'string') ? BEEM_ASSET_BASE : '../assets/';");
// 2. the streak file's CommonJS export is meaningless inside the closure
body = body.replace("if (typeof module !== 'undefined') module.exports = {streakState: streakState, GRACE_REFILL: GRACE_REFILL};", '');
// 3. the sheet builds all ten colours the moment it loads - seconds of work the
//    app must not pay on every Beem. The app builds one, on demand (tintReady
//    in beem-app-api.js), so that block is cut out here.
const ready = body.indexOf('var COLORS_READY = new Promise(');
if (ready < 0) throw new Error('COLORS_READY not found - beem-colors changed; update the build');
const end = body.indexOf('\n});', ready);
if (end < 0) throw new Error('end of COLORS_READY not found');
body = body.slice(0, ready) + '/* (COLORS_READY: the sheet\'s ten colours at load - cut by beem-build.mjs) */' + body.slice(end + 4);

const app = fs.readFileSync(L + 'beem-app-api.js', 'utf8');
const out = `/* GENERATED by dev/look/beem-build.mjs from ${SRC.join(', ')} and beem-app-api.js.
   Do not edit. Exposes one global: BeemKit. See dev/look/BEEM-INTEGRATION.md. */
(function(){
var BEEM_ASSET_BASE = window.BEEM_ASSET_BASE;
${body}
${app}
})();
`;
fs.writeFileSync(L + 'beem-app.js', out);
// the app fetches it from vendor/ (liveBase), so the stable app gets it only through a release
fs.writeFileSync(L + '../../vendor/beem-app.js', out);
console.log('beem-app.js', (out.length/1024).toFixed(1) + ' KB');
