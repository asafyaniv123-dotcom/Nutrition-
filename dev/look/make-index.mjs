  'sun-acts':     'שש פעולות קטנות — נוסע, מסתובב, נכנס בדלת, משקה צמח, יוצא מהכפתור, נרדם.',
  'sun-move':     'איך הוא זז ואיך הוא עוצר. קפיץ אחד, וכל השאר נגזר ממנו.',
