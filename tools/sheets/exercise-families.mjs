// difficulty: machines, cables, Smith and bands start; free weights are intermediate; bodyweight split by hand
const EASY_BW = ids('18 19 22 241 242 131 148 162 69 70 181 182 185 186 190 192 196 197 200 202 203 204 210 199 234 229 255 253 254 247 65');
const HARD = ids('225 226 227 228 93 156 157 191 188 201 147 172 31 23 57 129 194 248 198');
const EASY_X = ids('211 212 213 214 215 216 217 218 224');
const MID = ids('221 222');   // box jump and sled push are not beginner work whatever the tag says
const diff = (e, q) => MID.includes(e.id) ? 'בינוני' : HARD.includes(e.id) ? 'מתקדם' : EASY_BW.includes(e.id) || EASY_X.includes(e.id) ? 'מתחיל'
  : ['מכונה', 'פולי', "סמית' מאשין", 'גומייה'].includes(q) ? 'מתחיל' : 'בינוני';
const seen = new Set();
const res = F.map(([p, m, s, list]) => ({ parent_exercise: p, primary_muscle: m, secondary_muscles: s,
  variants: ids(list).map(id => { if (!byId[id]) throw Error('no ' + id); if (seen.has(id)) throw Error('twice ' + id); seen.add(id);
    const e = byId[id], q = equip(e); return { id, name: e.n, equipment: q, difficulty: diff(e, q) }; }) }));
const missing = ex.filter(e => !seen.has(e.id)).map(e => e.id);
if (missing.length) throw Error('missing ' + missing.join(','));
fs.writeFileSync(out, JSON.stringify(res, null, 2) + '\n');
// compact form for pasting: one variant per line
const compact = '[\n' + res.map(f => `  {"parent_exercise":${JSON.stringify(f.parent_exercise)},"primary_muscle":${JSON.stringify(f.primary_muscle)},"secondary_muscles":${JSON.stringify(f.secondary_muscles)},"variants":[\n` +
  f.variants.map(v => '    ' + JSON.stringify(v)).join(',\n') + '\n  ]}').join(',\n') + '\n]\n';
fs.writeFileSync(out.replace(/\.json$/, '.compact.json'), compact);
const n = k => res.flatMap(f => f.variants).filter(v => v.difficulty === k).length;
