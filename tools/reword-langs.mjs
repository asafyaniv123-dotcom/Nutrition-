/* Labels that sit beside one another and must stay distinct. */
const GROUPS = [
  ['פירוק מדויק', 'פירוק משוער', 'פירוק גס'],
  ['ערב רגוע', 'שיהיה ערב נעים', 'ערב נפלא'],
  ['צהריים נפלאים', 'שיהיה המשך יום מצוין', 'אמצע היום'],
];
const holes = s => (String(s).match(/\{\w+\}/g) || []).sort().join(',');

const list = process.argv.includes('--list');
let bad = 0;
for (const code in L) {
  const f = 'data/lang/' + code + '.json', d = JSON.parse(fs.readFileSync(f, 'utf8'));
  let n = 0;
  for (const num in L[code]) {
    const key = k(+num), v = L[code][num];
    if (!key || !(key in d)) { console.log(code + ': no key #' + num); bad++; continue; }
    if (typeof d[key] !== 'string') { console.log(code + ': #' + num + ' is a plural object, not rewritten'); bad++; continue; }
    if (holes(v) !== holes(EN[key])) { console.log(code + ': #' + num + ' placeholders ' + holes(v) + ' != ' + holes(EN[key])); bad++; }
    if (d[key] === v) continue;
    if (list) console.log(code + ' #' + num + '  ' + JSON.stringify(d[key]) + '\n    -> ' + JSON.stringify(v));
    d[key] = v; n++;
  }
  /* only the keys this script writes are held to it: fr, pt and ja already
   * answer two of the greeting siblings alike, which is theirs to keep */
  const before = bad;
  for (const g of GROUPS) for (const x of g) {
    if (!K.includes(x)) continue;
    const others = g.filter(y => y !== x).map(y => String(d[y]).toLowerCase());
    if (others.includes(String(d[x]).toLowerCase())) { console.log(code + ': ' + x + ' not distinct: ' + JSON.stringify(g.map(y => d[y]))); bad++; }
  }
  if (bad > before) continue;
  if (!list) fs.writeFileSync(f, JSON.stringify(d, null, 2) + '\n');
  console.log(code + ': ' + n + ' answers rewritten');
}
if (bad) { console.log(bad + ' problems, nothing written for the languages that had them'); process.exit(1); }
